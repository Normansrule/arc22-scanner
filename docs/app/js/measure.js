// Measurement editor → measurements/my_units.toml (read by cad/arc22_params.py).
import { download, el, getJSON, store } from "./app.js";

export async function initMeasure() {
  const data = await getJSON("data/params.json");
  const rows = data.measured;
  const known = new Set(rows.map((r) => r.key));
  let mine = store.get("measure", {});
  const status = document.getElementById("m-status");
  const say = (t, bad = false) => { status.textContent = t; status.style.color = bad ? "var(--stop)" : ""; };

  const host = document.getElementById("m-groups");
  const chips = {};
  const inputs = {};
  const byGroup = new Map();
  for (const r of rows) {
    if (!byGroup.has(r.group)) byGroup.set(r.group, []);
    byGroup.get(r.group).push(r);
  }

  const isSet = (k) => typeof mine[k] === "number" && Number.isFinite(mine[k]);

  const refreshChip = (k) => {
    const c = chips[k];
    const ok = isSet(k);
    c.className = "chip " + (ok ? "ok" : "ref");
    c.textContent = ok ? "Measured" : "Reference value";
  };

  const refreshCount = () => {
    const n = rows.filter((r) => isSet(r.key)).length;
    document.getElementById("m-count").textContent = `${n} of ${rows.length} measured`;
    document.getElementById("m-bar").style.width = `${(100 * n) / rows.length}%`;
    for (const [g, list] of byGroup) {
      const span = document.getElementById("g-" + g.replace(/\W/g, ""));
      if (span) span.textContent = `${list.filter((r) => isSet(r.key)).length} / ${list.length}`;
    }
  };

  for (const [g, list] of byGroup) {
    const sec = el("section", { class: "mgroup" },
      el("h2", {}, g, el("span", { id: "g-" + g.replace(/\W/g, "") })));
    for (const r of list) {
      const id = "m-" + r.key;
      const input = el("input", {
        id, type: "number", step: "any", inputmode: "decimal", placeholder: String(r.nominal),
        "aria-describedby": id + "-d",
      });
      if (isSet(r.key)) input.value = mine[r.key];
      input.addEventListener("input", () => {
        const v = input.value.trim() === "" ? null : Number(input.value);
        if (v === null || Number.isNaN(v)) delete mine[r.key];
        else mine[r.key] = v;
        store.set("measure", mine);
        refreshChip(r.key);
        refreshCount();
      });
      inputs[r.key] = input;
      chips[r.key] = el("span", { class: "chip" });
      sec.append(el("div", { class: "mrow" },
        el("div", { class: "what" },
          el("label", { for: id }, el("b", { text: r.label })),
          el("span", { id: id + "-d", text: `${r.source} (${r.key})` })),
        el("span", { class: "nom", text: `ref ${r.nominal}` }),
        input,
        chips[r.key]));
    }
    host.append(sec);
  }
  rows.forEach((r) => refreshChip(r.key));
  refreshCount();

  const toml = () => {
    const lines = [
      "# ARC-22 — measured values for MY parts (generated by ARC-22 Studio)",
      `# ${new Date().toISOString().slice(0, 10)}: save as measurements/my_units.toml, then run: bash scripts/rebuild_all.sh`,
      "# Units: millimetres. Commented lines keep their reference value and stay flagged VERIFY.",
      "",
      "[measured]",
    ];
    for (const [g, list] of byGroup) {
      lines.push(`# --- ${g}`);
      for (const r of list) {
        lines.push(isSet(r.key) ? `${r.key} = ${mine[r.key]}` : `# ${r.key} = ${r.nominal}    # ${r.label} (reference)`);
      }
    }
    return lines.join("\n") + "\n";
  };

  document.getElementById("m-download").addEventListener("click", () => {
    download("my_units.toml", toml(), "application/toml");
    say("Downloaded my_units.toml. Move it into the measurements folder of the repository.");
  });
  document.getElementById("m-copy").addEventListener("click", async () => {
    try { await navigator.clipboard.writeText(toml()); say("Copied the file contents."); }
    catch { say("Copy is blocked here. Use Download instead.", true); }
  });
  document.getElementById("m-clear").addEventListener("click", () => {
    if (!confirm("Clear every value you typed? The reference values stay.")) return;
    mine = {};
    store.set("measure", mine);
    for (const r of rows) { inputs[r.key].value = ""; refreshChip(r.key); }
    refreshCount();
    say("Cleared.");
  });
  document.getElementById("m-load").addEventListener("change", async (e) => {
    const f = e.target.files?.[0];
    if (!f) return;
    const text = await f.text();
    let section = "", n = 0;
    const unknown = [];
    for (const raw of text.split(/\r?\n/)) {
      const line = raw.replace(/#.*/, "").trim();
      if (!line) continue;
      const sec = line.match(/^\[(.+)\]$/);
      if (sec) { section = sec[1].trim(); continue; }
      const kv = line.match(/^([A-Za-z0-9_]+)\s*=\s*(-?[0-9.eE+-]+)$/);
      if (!kv || section !== "measured") continue;
      if (!known.has(kv[1])) { unknown.push(kv[1]); continue; }
      mine[kv[1]] = Number(kv[2]);
      inputs[kv[1]].value = kv[2];
      refreshChip(kv[1]);
      n++;
    }
    store.set("measure", mine);
    refreshCount();
    say(`Loaded ${n} values from ${f.name}.` + (unknown.length ? ` Ignored unknown keys: ${unknown.join(", ")}.` : ""),
      unknown.length > 0);
    e.target.value = "";
  });
}
