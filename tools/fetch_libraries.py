#!/usr/bin/env python3
"""
fetch_libraries.py — pull the two git-pinned firmware components and prepare them.

    python tools/fetch_libraries.py --camera plus      # Arducam Mini 2MP PLUS
    python tools/fetch_libraries.py --camera mini      # Arducam Mini 2MP (non-Plus)
    python tools/fetch_libraries.py --secrets          # write firmware/main/secrets.h from .env

What it does (nothing else is downloaded here — the ESP-IDF component manager fetches
arduino-esp32, esp-dl and coco_detect, including the model weights, during `idf.py build`):
  1. clones LovyanGFX at tag 1.2.28 and ArduCAM/Arduino at commit 066a7ea into
     firmware/components/, and refuses to continue if the checked-out commit differs
     from firmware/PINNED_VERSIONS.json
  2. makes LovyanGFX build against the Arduino component (the line its own CMake
     file asks you to enable)
  3. wraps ArduCAM as an ESP-IDF component, writes memorysaver.h for YOUR camera,
     and neutralises its `swap` macro (it collides with the C++ standard library)
  4. records what it did in firmware/components/FETCHED.json
Safe to re-run.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FW = ROOT / "firmware"
COMP = FW / "components"
PINS = json.loads((FW / "PINNED_VERSIONS.json").read_text())


def run(*cmd, cwd=None):
    print("  $", " ".join(cmd))
    subprocess.run(cmd, cwd=cwd, check=True)


def head(repo: pathlib.Path) -> str:
    return subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo, check=True, capture_output=True,
                          text=True).stdout.strip()


def fetch(name: str, url: str, ref: str, commit: str, dest: pathlib.Path) -> None:
    if dest.exists() and (dest / ".git").exists():
        run("git", "fetch", "--tags", "--quiet", "origin", cwd=dest)
    else:
        if dest.exists():
            shutil.rmtree(dest)
        run("git", "clone", "--quiet", "--filter=blob:none", url, str(dest))
    run("git", "-c", "advice.detachedHead=false", "checkout", "--quiet", "--force", ref, cwd=dest)
    got = head(dest)
    if got != commit:
        sys.exit(f"STOP: {name} is at {got}, but PINNED_VERSIONS.json expects {commit}")
    print(f"  {name}: {got[:12]} (verified)")


def prepare_lovyangfx(dest: pathlib.Path) -> None:
    cm = dest / "boards.cmake" / "esp-idf.cmake"
    s = cm.read_text()
    s2 = s.replace("# list(APPEND COMPONENT_REQUIRES arduino-esp32)", "list(APPEND COMPONENT_REQUIRES arduino-esp32)")
    if s2 != s:
        cm.write_text(s2)
        print("  LovyanGFX: enabled the arduino-esp32 requirement")


MEMSAVER = """#ifndef _MEMORYSAVER_
#define _MEMORYSAVER_
// Generated by tools/fetch_libraries.py for: {label}
// Only ONE ArduCAM-Mini platform may be defined.
#define {macro}
#endif
"""


def prepare_arducam(clone: pathlib.Path, camera: str) -> pathlib.Path:
    comp = COMP / "ArduCAM"
    comp.mkdir(parents=True, exist_ok=True)
    src = clone / PINS["git_components"]["ArduCAM"]["subdir"]
    for f in src.glob("*"):
        if f.suffix in (".h", ".cpp") or f.name == "LICENSE.txt":
            shutil.copy2(f, comp / f.name)
    hdr = comp / "ArduCAM.h"
    h = hdr.read_text(errors="replace")
    h = re.sub(r"^(\s*)#define swap\(type, i, j\).*$", r"\1/* swap macro removed by arc22 (clashes with std::swap) */",
               h, flags=re.M)
    hdr.write_text(h)
    macro, label = {"plus": ("OV2640_MINI_2MP_PLUS", "Arducam Mini 2MP Plus (OV2640)"),
                    "mini": ("OV2640_MINI_2MP", "Arducam Mini 2MP (OV2640)")}[camera]
    (comp / "memorysaver.h").write_text(MEMSAVER.format(label=label, macro=macro))
    (comp / "CMakeLists.txt").write_text(
        '# ArduCAM (ArduCAM/Arduino @ ' + PINS["git_components"]["ArduCAM"]["commit"][:7] + ') wrapped by arc22\n'
        'idf_component_register(SRCS "ArduCAM.cpp" INCLUDE_DIRS "." REQUIRES arduino-esp32)\n'
        'target_compile_options(${COMPONENT_LIB} PRIVATE -Wno-unused-variable -Wno-unused-but-set-variable '
        '-Wno-narrowing -Wno-error)\n')
    print(f"  ArduCAM: component ready for {label}")
    return comp


def write_secrets() -> None:
    env = ROOT / ".env"
    if not env.exists():
        sys.exit("No .env found. Copy .env.example to .env and fill in WIFI_SSID / WIFI_PASSWORD.")
    vals = {}
    for line in env.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            vals[k.strip()] = v.strip().strip('"').strip("'")
    ssid, pw = vals.get("WIFI_SSID", ""), vals.get("WIFI_PASSWORD", "")
    if not ssid:
        sys.exit(".env has no WIFI_SSID")

    def esc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"')

    out = FW / "main" / "secrets.h"
    out.write_text("// GENERATED from .env by tools/fetch_libraries.py --secrets. NEVER commit this file.\n"
                   "#pragma once\n"
                   f'#define ARC_WIFI_SSID "{esc(ssid)}"\n#define ARC_WIFI_PASSWORD "{esc(pw)}"\n')
    print(f"  wrote {out.relative_to(ROOT)} (git-ignored)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--camera", choices=["plus", "mini"], help="which Arducam Mini you have (read the PCB)")
    ap.add_argument("--secrets", action="store_true", help="generate firmware/main/secrets.h from .env")
    a = ap.parse_args()
    if not a.camera and not a.secrets:
        ap.error("give --camera plus|mini and/or --secrets")
    if a.camera:
        COMP.mkdir(parents=True, exist_ok=True)
        lg = PINS["git_components"]["LovyanGFX"]
        fetch("LovyanGFX", lg["git"], lg["tag"], lg["commit"], COMP / "LovyanGFX")
        prepare_lovyangfx(COMP / "LovyanGFX")
        ac = PINS["git_components"]["ArduCAM"]
        cache = FW / ".cache" / "ArduCAM-Arduino"
        cache.parent.mkdir(exist_ok=True)
        fetch("ArduCAM", ac["git"], ac["commit"], ac["commit"], cache)
        prepare_arducam(cache, a.camera)
        (COMP / "FETCHED.json").write_text(json.dumps(dict(
            camera=a.camera, LovyanGFX=head(COMP / "LovyanGFX"), ArduCAM=head(cache)), indent=2))
    if a.secrets:
        write_secrets()
    print("done. Next: cd firmware && idf.py set-target esp32s3 && idf.py build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
